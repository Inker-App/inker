// swift-tools-version: 6.0
// INKER: the macOS shell. See BUILD.md. Run app/scripts/build-rust.sh first so
// Frameworks/InkerCoreFFI.xcframework exists.
import PackageDescription

let package = Package(
    name: "INKER",
    // Decision 5.11 sets the floor at macOS 26, and Info.plist says so
    // (LSMinimumSystemVersion 26.0). VERIFY: `.macOS(.v26)` only exists in
    // PackageDescription 6.2+ (Xcode 26), so with tools-version 6.0 we declare
    // .v15 here. If you move to `swift-tools-version: 6.2`, switch to .v26.
    platforms: [.macOS(.v15)],
    products: [
        .executable(name: "INKER", targets: ["InkerApp"]),
    ],
    targets: [
        // Built by scripts/build-rust.sh from core/crates/inker-ffi.
        .binaryTarget(name: "InkerCoreFFI", path: "Frameworks/InkerCoreFFI.xcframework"),

        // UniFFI-generated Swift bindings (regenerated by scripts/build-rust.sh).
        // include/ holds the C header and module map; they ship inside the
        // xcframework, so the Swift target ignores them.
        .target(
            name: "InkerCore",
            dependencies: ["InkerCoreFFI"],
            path: "Sources/InkerCore",
            exclude: ["include"],
            linkerSettings: [
                // The Rust static lib pulls in chrono's time-zone lookup, which
                // uses CoreFoundation on macOS. VERIFY against the
                // `native-static-libs` line build-rust.sh prints.
                .linkedFramework("CoreFoundation"),
            ]
        ),

        // Pure logic, no AppKit: ink-grid math, eye state, reaction-diffusion,
        // octopus rig, drop collection, folder warnings, the queue view-model.
        .target(
            name: "InkerKit",
            dependencies: ["InkerCore"],
            path: "Sources/InkerKit"
        ),

        // AppKit shell, SwiftUI views, Metal renderers.
        .executableTarget(
            name: "InkerApp",
            dependencies: ["InkerKit", "InkerCore"],
            path: "Sources/InkerApp",
            resources: [
                // Archivo and JetBrains Mono (both SIL OFL 1.1, licences beside them).
                .copy("Resources/Fonts"),
                // Shader sources. Copied, not processed: the loader tries a
                // compiled default.metallib first and falls back to compiling
                // these at runtime (see Render/Metal/MetalLibraryLoader.swift).
                .copy("Render/Shaders"),
            ]
        ),

        // Swift Testing. `swift test` on a Mac.
        .testTarget(
            name: "InkerAppTests",
            dependencies: ["InkerKit", "InkerCore"],
            path: "Tests/InkerAppTests"
        ),
    ],
    // VERIFY: `swiftLanguageModes` is the Swift 6.0 name (SE-0441) for the old
    // `swiftLanguageVersions`. Swift 5 mode keeps strict-concurrency checking
    // from turning AppKit glue that cannot be compiled here into errors; the
    // code is written to be Swift 6 clean where practical.
    swiftLanguageModes: [.v5]
)
